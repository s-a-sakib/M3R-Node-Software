package com.m3rwallet.util;

import org.bouncycastle.asn1.x9.X9ECParameters;
import org.bouncycastle.crypto.digests.KeccakDigest;
import org.bouncycastle.crypto.ec.CustomNamedCurves;
import org.bouncycastle.crypto.params.ECDomainParameters;
import org.bouncycastle.crypto.params.ECPublicKeyParameters;
import org.bouncycastle.crypto.signers.ECDSASigner;
import org.bouncycastle.jce.ECNamedCurveTable;
import org.bouncycastle.jce.provider.BouncyCastleProvider;
import org.bouncycastle.jce.spec.ECNamedCurveParameterSpec;
import org.bouncycastle.jce.spec.ECPublicKeySpec;
import org.bouncycastle.math.ec.ECPoint;

import java.math.BigInteger;
import java.security.*;
import java.util.Arrays;

public class CryptoUtil {

    static {
        if (Security.getProvider(BouncyCastleProvider.PROVIDER_NAME) == null) {
            Security.addProvider(new BouncyCastleProvider());
        }
    }

    public static byte[] keccak256(byte[] message) {
        KeccakDigest digest = new KeccakDigest(256);
        byte[] hash = new byte[digest.getDigestSize()];
        if (message != null && message.length > 0) {
            digest.update(message, 0, message.length);
        }
        digest.doFinal(hash, 0);
        return hash;
    }

    /**
     * Verifies ASN.1 DER encoded ECDSA signature (used in standard client wallet transactions).
     */
    public static boolean verifySignature(byte[] msgHash, byte[] signatureBytes, byte[] pubKeyBytes) {
        try {
            ECNamedCurveParameterSpec spec = ECNamedCurveTable.getParameterSpec("secp256k1");
            KeyFactory kf = KeyFactory.getInstance("ECDSA", "BC");
            ECPoint q = spec.getCurve().decodePoint(pubKeyBytes);
            ECPublicKeySpec pubKeySpec = new ECPublicKeySpec(q, spec);
            PublicKey pk = kf.generatePublic(pubKeySpec);

            Signature signer = Signature.getInstance("NONEwithECDSA", "BC");
            signer.initVerify(pk);
            signer.update(msgHash);
            return signer.verify(signatureBytes);
        } catch (Exception e) {
            System.err.println("Crypto verification error: " + e.getMessage());
            return false;
        }
    }

    /**
     * Formats (r, s) into canonical 64-byte raw signature with strict canonical low-s (s <= n/2).
     */
    public static byte[] formatRawSignature(BigInteger r, BigInteger s) {
        X9ECParameters params = CustomNamedCurves.getByName("secp256k1");
        BigInteger n = params.getN();
        BigInteger halfN = n.shiftRight(1);
        if (s.compareTo(halfN) > 0) {
            s = n.subtract(s);
        }

        byte[] res = new byte[64];
        byte[] rBytes = r.toByteArray();
        byte[] sBytes = s.toByteArray();
        int rSrc = Math.max(0, rBytes.length - 32);
        int rDst = Math.max(0, 32 - rBytes.length);
        int rLen = Math.min(32, rBytes.length);
        System.arraycopy(rBytes, rSrc, res, rDst, rLen);

        int sSrc = Math.max(0, sBytes.length - 32);
        int sDst = 32 + Math.max(0, 32 - sBytes.length);
        int sLen = Math.min(32, sBytes.length);
        System.arraycopy(sBytes, sSrc, res, sDst, sLen);
        return res;
    }

    /**
     * Verifies raw 64-byte (r || s) secp256k1 signature generated by NodeIdentityService.
     * Enforces strict canonical low-s: 1 <= r < n and 1 <= s <= n/2.
     */
    public static boolean verifyRawSecp256k1Signature(byte[] data, byte[] signature64, byte[] pubKeyCompressed) {
        try {
            if (data == null || signature64 == null || signature64.length != 64 || pubKeyCompressed == null) {
                return false;
            }
            X9ECParameters params = CustomNamedCurves.getByName("secp256k1");
            ECDomainParameters domain = new ECDomainParameters(params.getCurve(), params.getG(), params.getN(), params.getH());
            ECPoint q = domain.getCurve().decodePoint(pubKeyCompressed);
            ECPublicKeyParameters pubKey = new ECPublicKeyParameters(q, domain);

            byte[] rBytes = Arrays.copyOfRange(signature64, 0, 32);
            byte[] sBytes = Arrays.copyOfRange(signature64, 32, 64);
            BigInteger r = new BigInteger(1, rBytes);
            BigInteger s = new BigInteger(1, sBytes);

            BigInteger n = domain.getN();
            BigInteger halfN = n.shiftRight(1);
            if (r.compareTo(BigInteger.ONE) < 0 || r.compareTo(n) >= 0
                    || s.compareTo(BigInteger.ONE) < 0 || s.compareTo(halfN) > 0) {
                return false;
            }

            ECDSASigner signer = new ECDSASigner();
            signer.init(false, pubKey);
            return signer.verifySignature(data, r, s);
        } catch (Exception e) {
            return false;
        }
    }

    /**
     * Checks if the given bytes represent a valid secp256k1 public key.
     */
    public static boolean isValidSecp256k1PublicKey(byte[] pubKeyBytes) {
        if (pubKeyBytes == null) return false;
        if (pubKeyBytes.length != 33 && pubKeyBytes.length != 65) return false;
        try {
            X9ECParameters params = CustomNamedCurves.getByName("secp256k1");
            ECPoint q = params.getCurve().decodePoint(pubKeyBytes);
            return q != null && !q.isInfinity() && q.isValid();
        } catch (Exception e) {
            return false;
        }
    }

    /**
     * Verifies either raw 64-byte (r || s) or ASN.1 DER ECDSA signature against data/digest.
     */
    public static boolean verifyVoteSignature(byte[] data, byte[] signatureBytes, byte[] pubKeyBytes) {
        if (data == null || signatureBytes == null || pubKeyBytes == null) {
            return false;
        }
        if (signatureBytes.length == 64) {
            return verifyRawSecp256k1Signature(data, signatureBytes, pubKeyBytes);
        }
        return verifySignature(data, signatureBytes, pubKeyBytes);
    }
}
